import asyncio, sys, os
from playwright.async_api import async_playwright
SP=sys.argv[1] if len(sys.argv)>1 else 'test-output'; os.makedirs(SP, exist_ok=True); B=os.environ.get('MARE_URL','http://127.0.0.1:8765/')
async def main():
    async with async_playwright() as p:
        br=await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        errs=[]
        async def run(name,w,h,scheme):
            ctx=await br.new_context(viewport={'width':w,'height':h}, color_scheme=scheme)
            pg=await ctx.new_page()
            pg.on('console', lambda m: m.type=='error' and errs.append(f'{name}: {m.text}'))
            pg.on('pageerror', lambda e: errs.append(f'{name} PAGEERR: {e}'))
            await pg.goto(B)
            await pg.fill('input[name=user]','demo'); await pg.fill('input[name=pass]','secret'); await pg.click('button[type=submit]')
            await pg.wait_for_selector('.sheet', timeout=5000)
            print(name,'connect sheet shown')
            await pg.fill('.sheet input[name=token]','bad'); await pg.click('.sheet button[type=submit]'); await pg.wait_for_timeout(500)
            print(name,'bad token msg:', await pg.text_content('.sheet-error'))
            await pg.fill('.sheet input[name=token]','good'); await pg.click('.sheet button[type=submit]')
            await pg.wait_for_selector('.mfy-card:not(.skel)', timeout=8000); await pg.wait_for_timeout(2500)
            print(name,'MFY cards:', await pg.locator('.mfy-card').count(), 'stations:', await pg.locator('.station').count(),
                  'top songs:', await pg.locator('#lb-top-songs .track').count(), 'top artists:', await pg.locator('.section:has-text("Top Artists") .card').count())
            await pg.screenshot(path=f'{SP}/r2-{name}-home.png')
            await pg.click('.mfy-card >> nth=0'); await pg.wait_for_selector('#lb-have .track', timeout=8000); await pg.wait_for_timeout(500)
            print(name,'LB playlist meta:', await pg.text_content('#lb-meta'), '| missing:', await pg.locator('.miss').count())
            await pg.screenshot(path=f'{SP}/r2-{name}-lbpl.png', full_page=False)
            await pg.click('[data-act="lb-play"]'); await pg.wait_for_timeout(800)
            print(name,'playing from LB playlist:', await pg.evaluate('Player.current()?.title'), 'queue', await pg.evaluate('Player.queue.length'))
            # station radio
            await pg.goto(B+'#/home'); await pg.wait_for_selector('.station', timeout=8000)
            await pg.click('[data-act="radio-station"]'); await pg.wait_for_timeout(1500)
            q0=await pg.evaluate('Player.queue.length'); lab=await pg.evaluate('Radio.label()')
            for _ in range(q0): await pg.evaluate('Player.next()'); await pg.wait_for_timeout(120)
            await pg.wait_for_timeout(1200)
            print(name,'station:',lab,'start queue',q0,'after skipping to end',await pg.evaluate('Player.queue.length'),'idx',await pg.evaluate('Player.index'))
            # recommended radio
            await pg.click('[data-act="radio-lb"]'); await pg.wait_for_timeout(2500)
            print(name,'lb radio:', await pg.evaluate('Radio.label()'), await pg.evaluate('Player.queue.length'))
            # song radio via menu + clearing radio on normal play
            await pg.goto(B+'#/album/al3'); await pg.wait_for_selector('.track')
            await pg.locator('.t-more >> nth=1').scroll_into_view_if_needed(); await pg.wait_for_timeout(600)  # the list scrolls smoothly
            await pg.click('.t-more >> nth=1', force=True); await pg.click('[data-mi=radio]'); await pg.wait_for_timeout(1500)
            print(name,'song radio:', await pg.evaluate('Radio.label()'), 'first:', await pg.evaluate('Player.current()?.title'))
            await pg.click('.track >> nth=0'); await pg.wait_for_timeout(300)
            print(name,'radio cleared on normal play:', await pg.evaluate('Radio.label()')=='')
            # artist radio button
            await pg.goto(B+'#/artist/ar2'); await pg.wait_for_selector('.hero-radio'); await pg.click('.hero-radio'); await pg.wait_for_timeout(1200)
            print(name,'artist radio:', await pg.evaluate('Radio.label()'))
            # lyrics: play song with synced lyrics (so1_2)
            await pg.goto(B+'#/album/al1'); await pg.wait_for_selector('.track'); await pg.click('.track >> nth=1'); await pg.wait_for_timeout(500)
            await pg.click('.p-now'); await pg.wait_for_timeout(500)
            await pg.click('.np-tab[data-view=lyrics]'); await pg.wait_for_timeout(600)
            await pg.evaluate('Player.audio.currentTime = 5.5'); await pg.wait_for_timeout(900)
            print(name,'lyric lines:', await pg.locator('.ly-line').count(), 'active:', await pg.text_content('.ly-line.on'))
            await pg.screenshot(path=f'{SP}/r2-{name}-lyrics.png')
            await pg.click('.ly-line >> nth=1'); await pg.wait_for_timeout(300)
            print(name,'seek by line ->', round(await pg.evaluate('Player.audio.currentTime')))
            await pg.click('.np-tab[data-view=queue]'); await pg.wait_for_timeout(300)
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(400)
            await pg.evaluate("Player.jump(2)"); await pg.wait_for_timeout(300)
            await pg.click('.p-now'); await pg.click('.np-tab[data-view=lyrics]'); await pg.wait_for_timeout(500)
            print(name,'no-lyrics msg:', await pg.text_content('.ly-msg'))
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
            await pg.goto(B+'#/settings'); await pg.wait_for_timeout(500)
            print(name,'settings:', (await pg.text_content('.settings'))[:90].replace('\n',' '))
            await pg.screenshot(path=f'{SP}/r2-{name}-settings.png')
            await pg.goto(B+'#/genre/Fado'); await pg.wait_for_selector('[data-act="radio-genre"]'); await pg.click('[data-act="radio-genre"]'); await pg.wait_for_timeout(800)
            print(name,'genre radio:', await pg.evaluate('Radio.label()'))
            await ctx.close()
        await run('desk',1400,880,'light')
        await run('mob',390,844,'dark')
        print('ERRORS:', errs or 'none')
        await br.close()
asyncio.run(main())
