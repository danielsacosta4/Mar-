#!/usr/bin/env bash
# Builds app/globe-lib.js: the country shapes (Natural Earth 110m, public domain, via world-atlas) and the few
# d3-geo / topojson-client functions the Collection globe needs (ISC / BSD licences), as one file for old Safari too.
# Run only when those packages should be refreshed; the result is committed.   build/globe.sh
set -euo pipefail
cd "$(dirname "$0")/.."
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
( cd "$T" && npm init -y >/dev/null && npm install --silent d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2 i18n-iso-countries@7.14.0 >/dev/null )
# ISO numeric (what the atlas uses) -> two-letter code (what MusicBrainz uses), only for countries on the map.
node -e '
const w = require(process.argv[1] + "/node_modules/world-atlas/countries-110m.json");
const iso = require(process.argv[1] + "/node_modules/i18n-iso-countries");
const out = {};
for (const g of w.objects.countries.geometries) { const a = g.id && iso.numericToAlpha2(g.id); if (a) out[g.id] = a; }
require("fs").writeFileSync(process.argv[1] + "/codes.json", JSON.stringify(out));
console.error("countries on the map:", w.objects.countries.geometries.length, "with a code:", Object.keys(out).length);
' "$T"
cat > "$T/entry.js" <<'JS'
import { geoOrthographic, geoPath, geoCentroid, geoGraticule10 } from 'd3-geo';
import { feature } from 'topojson-client';
import world from 'world-atlas/countries-110m.json';
import codes from './codes.json';
const countries = feature(world, world.objects.countries).features.map((f) => ({ code: codes[f.id] || '', name: f.properties.name, geo: f.geometry }));
window.MareGlobe = { geoOrthographic, geoPath, geoCentroid, geoGraticule10, countries };
JS
( cd "$T" && npx --yes esbuild@0.24.0 entry.js --bundle --minify --format=iife --target=safari12 --log-level=warning --outfile=out.js )
{ echo "/* Maré globe data + helpers. Generated by build/globe.sh: d3-geo (ISC), topojson-client (ISC), world-atlas / Natural Earth (public domain). */"; cat "$T/out.js"; } > app/globe-lib.js
echo "Built app/globe-lib.js ($(wc -c < app/globe-lib.js) bytes, $(gzip -c app/globe-lib.js | wc -c) gzipped)"
